"""
test_state_labels.py
────────────────────
Pins docs/specs/state_dependent_labels_spec.md: WATCH FOR on stand-aside
briefs, ENTRY / EXIT IF / TARGET on trade briefs, the over-promise guard
clause, and digest extraction under both labels.

Run: pytest tests/test_state_labels.py
"""
from _paths import ROOT
import re

import decision_brief as db


def _brief(decision, **over):
    kw = dict(instrument="GBP_AUD", timestamp="t", price=1.88, atr_pips=83.0,
              decision=decision, reason="r", conviction=0, grade="C",
              size_pct=0, market_state="m",
              invalidation="The low near 1.8732 confirms as a swing low.",
              regime_log="l", stand_down=(decision == "STAND DOWN"),
              override_fired=False, execution_mode="X", adx_d1=25.0,
              adx_h4=17.0, weekly_context="W", error=None)
    kw.update(over)
    return db.DecisionBrief(**kw)


def test_stand_aside_renders_watch_for_never_exit_if():
    out = _brief("STAND DOWN").format()
    assert "WATCH FOR" in out
    assert "EXIT IF" not in out
    assert "ENTRY" not in out and "TARGET" not in out

def test_trade_brief_renders_entry_exit_target_in_order():
    out = _brief("LONG", conviction=75, grade="A", size_pct=100,
                 entry_line="hourly support holding — level 1.8721",
                 target_line="not generated by the framework — set your "
                             "own; it must pay at least 1.5x what you risk "
                             "after the spread (the pre-trade check does "
                             "the math)").format()
    assert "WATCH FOR" not in out
    for label in ("ENTRY", "EXIT IF", "TARGET"):
        assert label in out
    assert out.index("ENTRY") < out.index("EXIT IF") < out.index("TARGET")
    flat = re.sub(r"\s+", " ", out)
    assert "level 1.8721" in flat
    assert "1.5x what you risk" in flat

def test_short_brief_same_slots():
    out = _brief("SHORT", entry_line="x", target_line="y").format()
    assert "EXIT IF" in out and "ENTRY" in out and "TARGET" in out


def test_guard_clause_on_concrete_watch_both_directions():
    from test_unconfirmed_trend import _regime
    down = db._build_invalidation(_regime(), "STAND DOWN")
    assert down.endswith("— the trade still depends on the filter, the "
                         "calendar, and a valid stop. Revisit then.")
    up = db._build_invalidation(_regime(
        d1_change_pips_10=250.0, d1_pending_high=1.926,
        d1_pending_high_age=4, d1_higher_lows=True,
        latest_sh=1.89716), "STAND DOWN")
    assert "the uptrend is confirmed then — the trade still depends" in up

def test_generic_watch_sentence_unchanged():
    from test_unconfirmed_trend import _regime
    out = db._build_invalidation(_regime(d1_lower_highs=False), "STAND DOWN")
    assert "stair-step" in out
    assert "still depends" not in out


def test_digest_watch_extraction_under_both_labels():
    import importlib.util, os
    spec = importlib.util.spec_from_file_location(
        "dd", os.path.join(ROOT,
                           "scripts", "daily_digest.py"))
    dd = importlib.util.module_from_spec(spec); spec.loader.exec_module(dd)
    text = ("  GBP/AUD  |  x\n  DECISION     STAND ASIDE — no\n\n"
            "  WATCH FOR    The low near 1.8732 confirms as a swing low"
            " — details. Revisit then.\n\n")
    line = dd.build_digest(text)
    assert "watch: The low near 1.8732 confirms as a swing low" in line
